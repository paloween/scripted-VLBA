"""Generate a standalone CASA calibration script from a user config.

The ALMA-style script template lives in ``templates/scriptForCalibration_VLBA.py``.
Everything between its BEGIN/END DATASET PARAMETERS markers is replaced with
values from the config; the rest is copied verbatim. The result runs in
monolithic CASA with ``casa -c`` or ``execfile`` and needs nothing from this
package.
"""
from __future__ import annotations

import datetime
from pathlib import Path

from .config import Config, ConfigError

TEMPLATE = Path(__file__).parent / "templates" / "scriptForCalibration_VLBA.py"
BEGIN = "# --- BEGIN DATASET PARAMETERS ---"
END = "# --- END DATASET PARAMETERS ---"

# (script variable, value getter, comment), in the order they appear.
_PARAMETERS = [
    ("vis", lambda c: c.vis, "output MS name after import"),
    ("fitsidi_files", lambda c: list(c.fitsidi_files), "FITS-IDI file(s), relative to where CASA starts"),
    ("antab_file", lambda c: c.antab_file, "ANTAB file (Tsys/gain curve), if needed"),
    ("obs_freq_ghz", lambda c: c.obs_freq_ghz, "drives the opacity/ionosphere branch (step 3)"),
    ("workdir", lambda c: c.workdir, "all products are written here"),
    ("refant", lambda c: c.refant, "reference antenna(s), in order of preference"),
    None,
    ("CALIBRATE_DELAY", lambda c: c.calibrate_delay, "fringe finder"),
    ("CALIBRATE_BANDPASS", lambda c: c.calibrate_bandpass, "bandpass calibrator"),
    ("CALIBRATE_PHASE", lambda c: c.calibrate_phase, "phase-referencing calibrator"),
    ("OBSERVE_TARGET", lambda c: c.observe_target, "science target"),
    None,
    ("quack_interval_s", lambda c: c.quack_interval_s, "flag this many seconds at scan start/end (step 2)"),
    ("tfcrop", lambda c: c.tfcrop, "automated tfcrop flagging (step 2)"),
    ("manual_flags", lambda c: c.manual_flags, "True: flag manual_flag_spw in step 2"),
    ("manual_flag_spw", lambda c: c.manual_flag_spw, "e.g. '0:0~3;124~127'"),
    ("sbd_timerange", lambda c: c.sbd_timerange, "good ~1 min range for instrumental delay (step 7)"),
    ("antpos", lambda c: c.antpos, "antenna-position corrections (step 5)"),
    ("phase_ref_target", lambda c: c.phase_ref_target, "self-cal the phase-ref cal and transfer to target (step 16)"),
    None,
    ("image_cell", lambda c: c.image_cell, "imaging cell size, e.g. '0.2mas', or 'auto' (steps 16-17)"),
    ("image_imsize", lambda c: c.image_imsize, "imaging size in pixels, e.g. 640, or 'auto' (steps 16-17)"),
    ("quicklook_calibrators", lambda c: c.quicklook_calibrators, "also make quicklook images of the calibrators (step 17)"),
]


def check_scriptable(config: Config) -> list[str]:
    """Problems that stop a config from becoming a standalone script."""
    problems = []
    if config.refant.strip().lower() == "auto":
        problems.append("refant='auto' needs the pipeline's refant heuristic, which the "
                        "standalone script does not have; set refant explicitly "
                        "(e.g. --refant FD)")
    if not config.calibrate_phase and config.phase_ref_target:
        problems.append("phase_ref_target=True needs 'calibrate_phase'")
    if config.overrides:
        problems.append("'overrides' are only supported by 'vlbapipe run'; edit the "
                        "generated script instead")
    return problems


def render_parameters(config: Config) -> str:
    lines = []
    for entry in _PARAMETERS:
        if entry is None:
            lines.append("")
            continue
        name, get, comment = entry
        assignment = f"{name} = {get(config)!r}"
        lines.append(f"{assignment:<37} # {comment}")
    return "\n".join(lines)


def generate_script(config: Config, source: str | None = None) -> str:
    """Return the CASA script text for ``config``."""
    problems = check_scriptable(config)
    if problems:
        raise ConfigError("Cannot generate script:\n  - " + "\n  - ".join(problems))

    template = TEMPLATE.read_text()
    start = template.index(BEGIN) + len(BEGIN)
    stop = template.index(END)
    body = template[:start] + "\n" + render_parameters(config) + "\n" + template[stop:]

    stamp = datetime.date.today().isoformat()
    origin = f" from {source}" if source else ""
    header = (f"# Generated by vlbapipe generate{origin} on {stamp}.\n"
              "# Re-generate rather than editing the parameter block by hand.\n#\n")
    return header + body


def write_script(config: Config, path: str | Path, source: str | None = None) -> Path:
    path = Path(path)
    text = generate_script(config, source=source)
    compile(text, str(path), "exec")  # catch template/rendering mistakes before CASA does
    path.write_text(text)
    return path
