"""The only module that touches CASA.

Stages call CASA tasks as ``ctx.casa.<task>(**kwargs)``. Every call is
recorded, so a run can be exported as a flat CASA script. The backend is
swappable: ``casatasks`` in production, a fake in tests.
"""
from __future__ import annotations

import importlib


class CasaAPI:
    def __init__(self, backend=None):
        self._backend = backend
        self.calls: list[tuple[str, dict]] = []

    def _resolve(self):
        if self._backend is None:
            try:
                self._backend = importlib.import_module("casatasks")
            except ImportError as e:
                raise RuntimeError(
                    "casatasks not found. Install the modular CASA packages "
                    "(pip install casatasks casatools) or run inside CASA.") from e
        return self._backend

    def __getattr__(self, task: str):
        if task.startswith("_"):
            raise AttributeError(task)

        def call(**kwargs):
            self.calls.append((task, dict(kwargs)))
            return getattr(self._resolve(), task)(**kwargs)

        return call

    def log(self, message: str, level: str = "INFO") -> None:
        print(message)
        try:
            self._resolve().casalog.post(message, level)
        except Exception:
            pass

    def antenna_coverage(self, vis: str) -> dict[str, float]:
        """Seconds each antenna spent on scans, for refant selection."""
        from casatools import msmd
        md = msmd()
        md.open(vis)
        try:
            names = md.antennanames()
            seconds = {n: 0.0 for n in names}
            for scan in md.scannumbers():
                t = md.timesforscan(scan)
                if len(t) == 0:
                    continue
                dur = float(t.max() - t.min())
                for a in md.antennasforscan(scan):
                    seconds[names[a]] += dur
            return seconds
        finally:
            md.close()

    def uv_extent(self, vis: str, field: str = "") -> dict[str, float]:
        """Longest unflagged baseline (m) and frequency span (Hz), for imaging heuristics."""
        from casatools import ms, msmetadata
        md = msmetadata()
        md.open(vis)
        try:
            lo, hi = [], []
            for spw in range(md.nspw()):
                f = md.chanfreqs(spw)
                w = abs(md.chanwidths(spw))
                lo.append(float((f - w / 2).min()))
                hi.append(float((f + w / 2).max()))
        finally:
            md.close()
        t = ms()
        t.open(vis)
        try:
            if field:
                t.msselect({"field": field})
            uvdist = t.range(["uvdist"])["uvdist"]
        finally:
            t.close()
        return {"max_uvdist_m": float(uvdist[1]),
                "min_freq_hz": min(lo), "max_freq_hz": max(hi)}

    def export_script(self, path: str) -> None:
        lines = ["# Generated by vlbapipe: the CASA task calls made during the run.\n"]
        for task, kw in self.calls:
            args = ", ".join(f"{k}={v!r}" for k, v in kw.items())
            lines.append(f"{task}({args})\n")
        with open(path, "w") as f:
            f.writelines(lines)
